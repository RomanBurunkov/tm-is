const { randomUUID } = require('crypto');
const { isUUID } = require('../../index');

describe('Test isUUID function', () => {
  const uuid = '123e4567-e89b-42d3-a456-426614174000';

  test('isUUID is defined', () => expect(isUUID).toBeDefined());

  test('returns false if no arguments are passed', () => {
    expect(isUUID()).toBe(false);
  });

  test('returns true for UUID versions 1 to 8 and all supported variants', () => {
    '12345678'.split('').forEach((version) => {
      '89ab'.split('').forEach((variant) => {
        expect(isUUID(`123e4567-e89b-${version}2d3-${variant}456-426614174000`)).toBe(true);
      });
    });
  });

  test('accepts uppercase UUIDs and UUIDs generated by Node.js', () => {
    expect(isUUID(uuid.toUpperCase())).toBe(true);
    expect(isUUID(randomUUID())).toBe(true);
  });

  test('returns true only if all arguments are valid UUIDs', () => {
    expect(isUUID(uuid, uuid.toUpperCase())).toBe(true);
    expect(isUUID(uuid, 'invalid')).toBe(false);
    expect(isUUID('invalid', uuid)).toBe(false);
  });

  test('rejects Nil and Max UUIDs', () => {
    expect(isUUID('00000000-0000-0000-0000-000000000000')).toBe(false);
    expect(isUUID('ffffffff-ffff-ffff-ffff-ffffffffffff')).toBe(false);
    expect(isUUID('FFFFFFFF-FFFF-FFFF-FFFF-FFFFFFFFFFFF')).toBe(false);
  });

  test('rejects invalid versions and variants', () => {
    ['0', '9', 'a', 'f'].forEach((version) => {
      expect(isUUID(`123e4567-e89b-${version}2d3-a456-426614174000`)).toBe(false);
    });
    ['0', '7', 'c', 'f'].forEach((variant) => {
      expect(isUUID(`123e4567-e89b-42d3-${variant}456-426614174000`)).toBe(false);
    });
  });

  test('rejects malformed strings', () => {
    [
      '',
      '123e4567e89b42d3a456426614174000',
      '123e4567_e89b-42d3-a456-426614174000',
      '123e4567-e89b-42d3-a456-42661417400g',
      ` ${uuid}`,
      `${uuid}\n`,
      `${uuid}x`,
      uuid.slice(0, -1),
    ].forEach((value) => expect(isUUID(value)).toBe(false));
  });

  test('rejects non-string values without coercion', () => {
    [null, undefined, 0, true, [], {}, Object(uuid)].forEach((value) => {
      expect(isUUID(value)).toBe(false);
    });
  });
});
